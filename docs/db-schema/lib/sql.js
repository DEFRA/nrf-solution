/**
 * A deliberately small SQL reader for the statements our migrations actually use.
 *
 * Both migration tools have an escape hatch to raw SQL — Liquibase `<sql>` and
 * Alembic `op.execute(...)` — and both are used for schema changes that matter:
 * `quotes.reference` is a generated column created only in raw SQL, and
 * `quote_edp_results` was dropped and recreated in raw SQL with a different
 * column set. A parser that skipped raw SQL would silently emit a wrong schema.
 *
 * The guiding rule is that this module never guesses. Every statement is either
 * recognised and applied, explicitly listed as harmless-to-ignore, or returned
 * as `unknown` so the generator can refuse to emit a document it cannot vouch
 * for. Adding a new kind of raw DDL should break the build, not corrupt the docs.
 */

/** Split on semicolons that are not inside quotes or a $tag$-quoted block. */
export function splitStatements(sql) {
  const out = []
  let buf = ''
  let quote = null // "'" | '"' | a dollar tag such as '$backfill$'

  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i]

    if (quote) {
      buf += ch
      if (quote.length === 1) {
        // '' and "" are escapes for a literal quote, so consume the pair
        if (ch === quote && sql[i + 1] === quote) {
          buf += sql[++i]
        } else if (ch === quote) {
          quote = null
        }
      } else if (ch === '$' && sql.startsWith(quote, i)) {
        buf += quote.slice(1)
        i += quote.length - 1
        quote = null
      }
      continue
    }

    if (ch === "'" || ch === '"') {
      quote = ch
      buf += ch
      continue
    }

    const dollar = /^\$[A-Za-z_]*\$/.exec(sql.slice(i))
    if (dollar) {
      quote = dollar[0]
      buf += dollar[0]
      i += dollar[0].length - 1
      continue
    }

    if (ch === ';') {
      out.push(buf)
      buf = ''
      continue
    }
    buf += ch
  }

  out.push(buf)
  return out.map((s) => s.replace(/--[^\n]*/g, '').trim()).filter(Boolean)
}

/**
 * Statements that cannot change the set of tables or columns we document.
 * Listed explicitly so that anything genuinely new is reported as unknown.
 */
const IGNORABLE = [
  /^CREATE\s+EXTENSION\b/i,
  // A type is a schema object but not a table; a column using one simply
  // reports that type by name, which is self-describing.
  /^CREATE\s+TYPE\b/i,
  /^DROP\s+TYPE\b/i,
  /^ALTER\s+TYPE\b/i,
  /^CREATE\s+SCHEMA\b/i,
  /^CREATE\s+(OR\s+REPLACE\s+)?(VIEW|FUNCTION|TRIGGER)\b/i,
  /^DROP\s+(VIEW|FUNCTION|TRIGGER)\b/i,
  /^GRANT\b/i,
  /^REVOKE\b/i,
  /^CREATE\s+(UNIQUE\s+)?INDEX\b/i, // indexes are collected separately
  /^DROP\s+INDEX\b/i,
  /^DELETE\s+FROM\b/i,
  /^UPDATE\b/i,
  /^INSERT\s+INTO\b/i,
  /^SELECT\b/i,
  /^PERFORM\b/i,
  /^DO\b/i, // procedural blocks: data backfills in every current use
  /^COMMENT\s+ON\b/i,
  /^ANALYZE\b/i,
  /^VACUUM\b/i,
  /^SET\b/i
]

const unquote = (s) => s.replace(/"/g, '').replace(/^public\./i, '').toLowerCase()

/**
 * Split a CREATE TABLE body on top-level commas — `DECIMAL(12, 2)` must not be
 * treated as two entries.
 */
function splitDefs(body) {
  const parts = []
  let depth = 0
  let buf = ''
  for (const ch of body) {
    if (ch === '(') depth++
    else if (ch === ')') depth--
    if (ch === ',' && depth === 0) {
      parts.push(buf)
      buf = ''
      continue
    }
    buf += ch
  }
  parts.push(buf)
  return parts.map((p) => p.trim()).filter(Boolean)
}

const TABLE_CONSTRAINT =
  /^(CONSTRAINT\b|PRIMARY\s+KEY\b|FOREIGN\s+KEY\b|UNIQUE\s*\(|CHECK\s*\(|EXCLUDE\b)/i

/** Parse one column definition out of a CREATE TABLE body. */
function parseColumnDef(def) {
  const m = /^("?[A-Za-z_][\w]*"?)\s+(.+)$/s.exec(def)
  if (!m) return null
  const name = unquote(m[1])
  const rest = m[2].trim()

  // The type is everything up to the first column constraint keyword.
  const typeMatch =
    /^([A-Za-z_][\w\s]*?(?:\([^)]*\))?(?:\s*\[\s*\])?)\s*(?=\b(?:NOT\s+NULL|NULL|PRIMARY|UNIQUE|REFERENCES|DEFAULT|GENERATED|CHECK|COLLATE)\b|$)/i.exec(
      rest
    )
  const type = (typeMatch ? typeMatch[1] : rest).trim().replace(/\s+/g, ' ')

  const generated = /GENERATED\s+ALWAYS\s+AS\s*\((.+)\)\s*STORED/is.exec(rest)
  const identity = /GENERATED\s+(?:ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY/i.test(rest)
  const fk = /REFERENCES\s+("?[\w.]+"?)\s*\(\s*("?\w+"?)\s*\)/i.exec(rest)

  // `GENERATED BY DEFAULT AS IDENTITY` contains the word DEFAULT but declares no
  // default value, so remove both GENERATED forms before looking for one.
  const withoutGenerated = rest
    .replace(/GENERATED\s+(?:ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY(\s*\([^)]*\))?/gi, ' ')
    .replace(/GENERATED\s+ALWAYS\s+AS\s*\(.+\)\s*STORED/gis, ' ')
  const def_ = /DEFAULT\s+((?:[^,]|\([^)]*\))+?)(?=\s+(?:NOT\s+NULL|NULL|UNIQUE|PRIMARY|REFERENCES|CHECK)\b|$)/i.exec(
    withoutGenerated
  )

  return {
    name,
    type,
    notNull: /NOT\s+NULL/i.test(rest) || /PRIMARY\s+KEY/i.test(rest),
    primaryKey: /PRIMARY\s+KEY/i.test(rest),
    unique: /\bUNIQUE\b/i.test(rest),
    identity,
    generatedAs: generated ? generated[1].trim().replace(/\s+/g, ' ') : null,
    default: def_ ? def_[1].trim() : null,
    references: fk ? { table: unquote(fk[1]), column: unquote(fk[2]) } : null,
    onDeleteCascade: fk ? /ON\s+DELETE\s+CASCADE/i.test(rest) : false
  }
}

/**
 * Classify one statement.
 *
 * Returns `{ op: 'unknown', sql }` for anything not recognised — callers are
 * expected to surface that rather than drop it.
 */
export function parseStatement(sql) {
  const s = sql.trim().replace(/\s+/g, ' ')

  let m = /^CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?("?[\w.]+"?)\s*\(([\s\S]+)\)\s*$/i.exec(
    sql.trim()
  )
  if (m) {
    const defs = splitDefs(m[2])
    const columns = []
    const constraints = []
    for (const d of defs) {
      if (TABLE_CONSTRAINT.test(d)) {
        constraints.push(d.replace(/\s+/g, ' '))
        continue
      }
      const col = parseColumnDef(d)
      if (col) columns.push(col)
    }
    return { op: 'createTable', table: unquote(m[1]), columns, constraints }
  }

  m = /^ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?("?[\w.]+"?)\s+ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?([\s\S]+)$/i.exec(
    sql.trim()
  )
  if (m) {
    const col = parseColumnDef(m[2].trim())
    return col
      ? { op: 'addColumn', table: unquote(m[1]), column: col }
      : { op: 'unknown', sql: s }
  }

  m = /^ALTER\s+TABLE\s+("?[\w.]+"?)\s+DROP\s+COLUMN\s+(?:IF\s+EXISTS\s+)?("?\w+"?)/i.exec(s)
  if (m) return { op: 'dropColumn', table: unquote(m[1]), column: unquote(m[2]) }

  m = /^ALTER\s+TABLE\s+("?[\w.]+"?)\s+ALTER\s+(?:COLUMN\s+)?("?\w+"?)\s+(.+)$/i.exec(s)
  if (m) {
    const table = unquote(m[1])
    const column = unquote(m[2])
    const action = m[3].trim()

    const type = /^(?:SET\s+DATA\s+)?TYPE\s+(.+?)(?:\s+USING\s+.+)?$/i.exec(action)
    if (type) return { op: 'alterColumn', table, column, type: type[1].trim() }
    if (/^SET\s+NOT\s+NULL$/i.test(action)) return { op: 'alterColumn', table, column, notNull: true }
    if (/^DROP\s+NOT\s+NULL$/i.test(action)) {
      return { op: 'alterColumn', table, column, notNull: false }
    }
    const dflt = /^SET\s+DEFAULT\s+(.+)$/i.exec(action)
    if (dflt) return { op: 'alterColumn', table, column, default: dflt[1].trim() }
    if (/^DROP\s+DEFAULT$/i.test(action)) return { op: 'alterColumn', table, column, default: null }
    // An ALTER we do not model (identity, storage, compression) — say so.
    return { op: 'unknown', sql: s }
  }

  m = /^ALTER\s+TABLE\s+("?[\w.]+"?)\s+RENAME\s+TO\s+("?\w+"?)/i.exec(s)
  if (m) return { op: 'renameTable', from: unquote(m[1]), to: unquote(m[2]) }

  m = /^ALTER\s+TABLE\s+("?[\w.]+"?)\s+RENAME\s+(?:COLUMN\s+)?("?\w+"?)\s+TO\s+("?\w+"?)/i.exec(s)
  if (m) {
    return { op: 'renameColumn', table: unquote(m[1]), from: unquote(m[2]), to: unquote(m[3]) }
  }

  m = /^DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?("?[\w.]+"?)/i.exec(s)
  if (m) return { op: 'dropTable', table: unquote(m[1]) }

  m = /^ALTER\s+TABLE\s+("?[\w.]+"?)\s+ADD\s+CONSTRAINT\s+("?\w+"?)\s+(.+)$/i.exec(s)
  if (m) {
    return { op: 'addConstraint', table: unquote(m[1]), name: unquote(m[2]), body: m[3] }
  }

  if (IGNORABLE.some((re) => re.test(s))) return { op: 'ignore', sql: s }

  return { op: 'unknown', sql: s }
}

/** Parse a raw SQL blob into an ordered list of classified statements. */
export const parseSql = (sql) => splitStatements(sql).map(parseStatement)
